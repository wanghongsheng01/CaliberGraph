"""Generate paper/numbers.tex (macros) and paper/tables/*.tex from results/test/summary.json.
Every number in the paper text that comes from an experiment must be a macro defined here.
Usage: python make_numbers.py --summary ../results/test/summary.json [--taxonomy ../results/test/taxonomy.json]
       [--dev ../results/dev_summary.json] --paper ../paper
"""
import argparse
import json
import os

TIER = {'L0': 'Lzero', 'L1': 'Lone', 'L1f': 'Lonef', 'L1n': 'Lonen', 'O1f': 'Oonef', 'O1n': 'Oonen', 'L2': 'Ltwo'}
METH = {'CaliberGraph': 'CG', 'CaliberGraph+SC': 'CGSC', 'ParSEval-L1': 'PV', 'ParSEval (official)': 'PVO',
        'Random fuzzing': 'FZ', 'SpotIt': 'SI', 'SpotIt+': 'SIP'}
TEST = {'H1': 'hOne', 'H2': 'hTwo', 'vs ParSEval-L1': 'vsPV', 'vs fuzzing': 'vsFZ', 'vs SpotIt+ claims (L1f)': 'vsSIP'}
REC = {'CaliberGraph': 'CG', 'ParSEval-L1': 'PV', 'Random fuzzing': 'FZ', 'SpotIt (claims)': 'SI'}


def fint(x):
    return f'{int(x):,}'.replace(',', '{,}')


def fpct(x, d=1):
    return f'{100 * x:.{d}f}'


def fp(p):
    if p == 0:
        return '<10^{-300}'
    if p >= 1e-3:
        return f'{p:.3f}'
    m, e = f'{p:.1e}'.split('e')
    return f'{m}\\times 10^{{{int(e)}}}'


def fsig(x):
    s = f'{x:+,d}'.replace(',', '{,}')
    return s.replace('-', '$-$')


class Out:
    def __init__(self):
        self.lines = ['% generated by src/make_numbers.py from results/test/summary.json -- do not edit by hand']

    def __call__(self, name, val):
        self.lines.append(f'\\newcommand{{\\{name}}}{{{val}\\xspace}}')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--summary', required=True)
    ap.add_argument('--taxonomy')
    ap.add_argument('--paper', required=True)
    ap.add_argument('--summary-r', dest='summary_r')
    ap.add_argument('--attr-v4', dest='attr_v4')
    ap.add_argument('--recert-r', dest='recert_r')
    ap.add_argument('--issues')
    a = ap.parse_args()
    S = json.load(open(a.summary))
    N = Out()
    n_exc = S['n_exc']
    N('nExc', fint(n_exc))
    N('nExi', fint(S['n_exi']))
    N('nQexc', fint(S['n_questions_exc']))
    N('nDistinctExc', fint(S['n_distinct_exc']))
    # ---- main counts
    for m, row in S['main'].items():
        k = METH[m]
        for t, tn in TIER.items():
            if t in row:
                N(f'n{k}{tn}', fint(row[t]))
                N(f'p{k}{tn}', fpct(row[t] / n_exc))
        for c, v in row['contracts_L1f'].items():
            N(f'n{k}Lonef{c.split("_")[1].capitalize()}', fint(v))
        if 'author_claims' in row:
            N(f'n{k}Claims', fint(row['author_claims']))
            N(f'p{k}Claims', fpct(row['author_claims'] / n_exc))
    cg = S['main'].get('CaliberGraph', {})
    if cg.get('L1f'):
        N('pCGNullDependent', fpct(1 - cg['L1n'] / cg['L1f'], 0))
    for nm in ('SpotIt', 'SpotIt+'):
        r = S['main'].get(nm)
        if r and r.get('author_claims'):
            N(f'p{METH[nm]}SurviveLonef', fpct(r['L1f'] / r['author_claims'], 1))
            N(f'p{METH[nm]}SurviveLzero', fpct(r['L0'] / r['author_claims'], 1))
    # ---- paired tests
    for t in S['tests']:
        k = TEST[t['label']]
        N(f'{k}A', fint(t['count_a']))
        N(f'{k}B', fint(t['count_b']))
        N(f'{k}Diff', fint(t['diff']) if t['diff'] >= 0 else '$-$' + fint(-t['diff']))
        N(f'{k}AOnly', fint(t['a_only']))
        N(f'{k}BOnly', fint(t['b_only']))
        lo, hi = t['ci95']
        N(f'{k}CI', f'[{fint(lo) if lo >= 0 else "$-$" + fint(-lo)}, {fint(hi) if hi >= 0 else "$-$" + fint(-hi)}]')
        N(f'{k}P', fp(t['p']))
        if 'p_holm' in t:
            N(f'{k}PHolm', fp(t['p_holm']))
    # ---- recall
    for nm, r in S.get('known_positive_recall', {}).items():
        k = REC[nm]
        if 'recall' in r:
            N(f'r{k}', fpct(r['recall']))
            N(f'r{k}N', fint(r['found']))
        else:
            for t in ('L0', 'L1', 'L1f', 'L1n', 'L2'):
                N(f'r{k}{TIER[t]}', fpct(r[t]))
            N(f'r{k}N', fint(r['found_L1f']))
    # ---- systems and ranking
    if 'per_system' in S:
        per = S['per_system']
        N('kendallTau', f'{S["kendall_tau_ex_vs_corrected"]:.2f}')
        N('kendallTauSpotIt', f'{S["kendall_tau_ex_vs_spotit_corrected"]:.2f}')
        shares = [v['fp_share'] for v in per.values()]
        N('fpShareMin', fpct(min(shares)))
        N('fpShareMax', fpct(max(shares)))
        drops = [v['ex'] - v['corrected'] for v in per.values()]
        N('exDropMin', fpct(min(drops)))
        N('exDropMax', fpct(max(drops)))
        moved = sum(1 for k in per if S['rank_ex'][k] != S['rank_corrected'][k])
        N('nRankChanged', str(moved))
        sg = S['schema_groups']
        N('rateHeldout', fpct(sg['held-out schemas']['rate']))
        N('rateOther', fpct(sg['other schemas']['rate']))
        for d, v in S['difficulty'].items():
            N(f'rate{d.capitalize()}', fpct(v['rate']))
        rows = []
        for k in sorted(per, key=lambda x: S['rank_ex'][x]):
            v = per[k]
            rows.append(f"{v['name']} & {fpct(v['ex'])} & {S['rank_ex'][k]} & {fint(v['spotit_fp'])} & {fint(v['cg_fp'])} & "
                        f"{fpct(v['fp_share'])} & {fpct(v['corrected'])} & {S['rank_corrected'][k]} \\\\")
        tab('systems', a.paper, [
            '\\begin{tabular}{lrrrrrrr}', '\\toprule',
            'System & EX (\\%) & Rank & SpotIt & CG & CG share (\\%) & Corrected (\\%) & Rank \\\\', '\\midrule',
            *rows, '\\bottomrule', '\\end{tabular}'])
    for nm, v in S.get('time_to_witness', {}).items():
        k = METH[nm]
        N(f't{k}Median', f'{v["median"]:.2f}')
        N(f't{k}Pninetyfive', f'{v["p95"]:.2f}')
        N(f't{k}WithinOne', fpct(v['curve'][4] / v['n']))
    if 'spotit_released_time' in S:
        N('tSpotItMedian', f'{S["spotit_released_time"]["median"]:.1f}')
        N('tSpotItHours', fint(round(S['spotit_released_time']['total_h'])))
    for k, v in S.get('h4_tests', {}).items():
        nm = {'-anchoring': 'NoAnchor', '-isolation': 'NoIso', '-join graph': 'NoJoin', '-SQLite domain': 'NoDomain'}[k]
        N(f'hFour{nm}P', fp(v['p']))
        N(f'hFour{nm}FullOnly', fint(v['full_only']))
        N(f'hFour{nm}AblOnly', fint(v['abl_only']))
    if 'h3' in S:
        N('hThreePHolm', fp(S['h3']['p_holm']))
    for t in S.get('h3_tests', []):
        k = {'ParSEval-L1': 'PV', 'SpotIt (claims)': 'SI', 'Random fuzzing': 'FZ'}[t['b']]
        N(f'hThree{k}AOnly', fint(t['a_only']))
        N(f'hThree{k}BOnly', fint(t['b_only']))
    if 'subsample' in S:
        sub = S['subsample']
        N('nSub', fint(sub['n']))
        names = {'full': 'Full', '-anchoring': 'NoAnchor', '-isolation': 'NoIso', '-join graph': 'NoJoin',
                 '-SQLite domain': 'NoDomain', 'full, 10 s': 'Ten', 'ParSEval-L1, 5 s': 'PVFive',
                 'ParSEval-L1, 10 s': 'PVTen'}
        for k, v in sub['counts'].items():
            N(f'sub{names[k]}', fint(v))
        full = sub['counts'].get('full')
        rows = []
        for k, v in sub['counts'].items():
            d = '' if (k == 'full' or full is None or k.startswith('ParSEval')) else f'{v - full:+d}'.replace('-', '$-$')
            rows.append(f'{k.replace("-", "$-$", 1) if k.startswith("-") else k} & {fint(v)} & {d} \\\\')
        tab('ablation', a.paper, ['\\begin{tabular}{lrr}', '\\toprule', 'Configuration & L1f witnesses & $\\Delta$ \\\\',
                                   '\\midrule', *rows, '\\bottomrule', '\\end{tabular}'])
    # ---- main table
    order = [m for m in ('CaliberGraph', 'CaliberGraph+SC', 'ParSEval-L1', 'ParSEval (official)', 'Random fuzzing',
                         'SpotIt', 'SpotIt+') if m in S['main']]
    rows = []
    for m in order:
        r = S['main'][m]
        claims = fint(r['author_claims']) if 'author_claims' in r else '--'
        cells = [fint(r[t]) for t in ('L0', 'L1f', 'L1n', 'L2')]
        has_o = False
        if has_o:
            cells.append(fint(r.get('O1n', 0)))
        name = '\\textbf{CaliberGraph}' if m == 'CaliberGraph' else m
        rows.append(f'{name} & {claims} & ' + ' & '.join(cells) + ' \\\\')
    has_o = False
    hdr = 'Method & Claimed & L0 & L1f & L1n & L2' + (' & O1n' if has_o else '') + ' \\\\'
    tab('main', a.paper, ['\\begin{tabular}{lrrrrr' + ('r' if has_o else '') + '}', '\\toprule', hdr, '\\midrule',
                          *rows, '\\bottomrule', '\\end{tabular}'])
    # ---- tests table
    rows = []
    for t in S['tests']:
        lo, hi = t['ci95']
        rows.append(f"{t['label'].replace('vs ', 'CG vs ')} & {t['a']} ({t['tier_a']}) & {t['b']} ({t['tier_b']}) & "
                    f"{fint(t['a_only'])} & {fint(t['b_only'])} & {fsig(t['diff'])} & [{fsig(lo)}, {fsig(hi)}] & ${fp(t.get('p_holm', t['p']))}$ \\\\")
    tab('tests', a.paper, ['\\begin{tabular}{lllrrrrr}', '\\toprule',
                           'Comparison & A & B & A only & B only & A$-$B & 95\\,\\% CI & $p$ \\\\', '\\midrule',
                           *rows, '\\bottomrule', '\\end{tabular}'])
    # ---- recall table
    rec = S.get('known_positive_recall', {})
    if rec:
        rows = []
        for nm, r in rec.items():
            if 'recall' in r:
                rows.append(f'{nm} & -- & {fpct(r["recall"])} & -- & -- \\\\')
            else:
                rows.append(f'{nm} & {fpct(r["L0"])} & {fpct(r["L1f"])} & {fpct(r["L1n"])} & {fpct(r["L2"])} \\\\')
        tab('recall', a.paper, ['\\begin{tabular}{lrrrr}', '\\toprule', 'Method & L0 & L1f & L1n & L2 \\\\', '\\midrule',
                                *rows, '\\bottomrule', '\\end{tabular}'])
    # ---- contracts table (appendix)
    rows = []
    for m in [x for x in ('CaliberGraph', 'CaliberGraph+SC', 'ParSEval-L1', 'Random fuzzing', 'SpotIt', 'SpotIt+') if x in S['main']]:
        c = S['main'][m]['contracts_L1f']
        rows.append(f"{m} & {fint(c['C_set'])} & {fint(c['C_bag'])} & {fint(c['C_lenient'])} \\\\")
    tab('contracts', a.paper, ['\\begin{tabular}{lrrr}', '\\toprule',
                               'Method & $\\mathcal C_{\\mathrm{set}}$ & $\\mathcal C_{\\mathrm{bag}}$ & $\\mathcal C_{\\mathrm{len}}$ \\\\',
                               '\\midrule', *rows, '\\bottomrule', '\\end{tabular}'])
    tf = os.path.join(os.path.dirname(a.summary), '..', 'test', 'audit', 'taxonomy_final.json')
    tf = tf if os.path.exists(tf) else os.path.join(os.path.dirname(__file__), '..', 'results', 'test', 'audit', 'taxonomy_final.json')
    if os.path.exists(tf):
        T = json.load(open(tf))
        lab = {'null_semantics': '\\texttt{NULL} handling', 'filter_predicate': 'Filter predicate', 'join_path': 'Join path',
               'order_limit_ties': 'Ordering, \\texttt{LIMIT}, ties', 'duplicates_distinct': 'Duplicates, \\texttt{DISTINCT}',
               'empty_aggregate': 'Aggregate over empty input', 'projection': 'Projection', 'numeric_type_division': 'Numeric type, division',
               'grouping': 'Grouping', 'other': 'Other'}
        rows = [f"{lab.get(k, k)} & {v['n']} & [{100 * v['ci95'][0]:.0f}, {100 * v['ci95'][1]:.0f}] \\\\" for k, v in T['primary'].items()]
        tab('taxonomy', a.paper, ['\\begin{tabular}{lrr}', '\\toprule', 'Primary root cause & \\% & 95\\,\\% CI \\\\', '\\midrule',
                                  *rows, '\\bottomrule', '\\end{tabular}'])
        N('taxKappa', f"{T['interannotator']['kappa']:.2f}")
        N('taxRulePrimary', fint(T['rule_vs_manual']['primary_in_rule_labels']))
    # ---- taxonomy
    if a.taxonomy and os.path.exists(a.taxonomy):
        T = json.load(open(a.taxonomy))
        N('nTaxonomy', fint(T['n']))
        for lab, v in T['counts'].items():
            N('tax' + ''.join(w.capitalize() for w in lab.split('_')), fint(v))
            N('ptax' + ''.join(w.capitalize() for w in lab.split('_')), fpct(v / T['n'], 0))
    numbers_r(a, N, n_exc)
    with open(os.path.join(a.paper, 'numbers.tex'), 'w') as f:
        f.write('\n'.join(N.lines) + '\n')
    print(len(N.lines) - 1, 'macros')


ATTR = {'CaliberGraph@L1f': 'CG', 'Fuzz@L1f': 'FZ', 'ParSEval-L1@L1f': 'PV', 'SpotIt@L0': 'SI', 'SpotIt+@L0': 'SIP',
        'CaliberGraph-R@R': 'CGR', 'Fuzz-R@R': 'FZR', 'ParSEval-R@R': 'PVR'}
RMETH = {'CaliberGraph-R': 'CGR', 'Fuzz-R': 'FZR', 'ParSEval-R': 'PVR', 'CaliberGraph': 'CG', 'CaliberGraph+SC': 'CGSC',
         'ParSEval-L1': 'PV', 'Fuzz': 'FZ', 'SpotIt': 'SI', 'SpotIt+': 'SIP'}


def numbers_r(a, N, n_exc):
    """Macros and tables for the attribution study and the second freeze (tier R)."""
    rows = []
    if a.attr_v4 and os.path.exists(a.attr_v4):
        A = json.load(open(a.attr_v4))
        ag = A['agreement']
        N('attrN', fint(ag['n']))
        N('attrAgree', fpct(ag['agree'] / ag['n'], 0))
        N('attrKappa', f"{ag['kappa']:.2f}")
        N('attrAdj', fint(ag['adjudicated']))
        imp, err = [], []
        for src, v in A['methods'].items():
            k = ATTR[src]
            c = v['counts']
            n = v['n']
            N(f'p{k}Impl', fpct(v['implausible_share'], 0))
            N(f'p{k}Meaningful', fpct(v['meaningful'] / n, 0))
            N(f'p{k}Err', fpct(v['errors'] / n, 0))
            N(f'est{k}Meaningful', fint(round(v['est_meaningful'])))
            N(f'est{k}MeaningfulCI', f"[{fint(round(v['est_meaningful_ci'][0]))}, {fint(round(v['est_meaningful_ci'][1]))}]")
            N(f'est{k}Err', fint(round(v['est_errors'])))
            imp.append(v['implausible_share'])
            err.append(v['errors'] / n)
            rows.append((src, v))
        ratios = [v['certified'] / v['est_errors'] for v in A['methods'].values() if v['est_errors']]
        N('ratioMin', str(int(min(ratios) + 0.5)))
        N('ratioMax', str(int(max(ratios) + 0.5)))
        N('attrImplMin', fpct(min(imp), 0))
        N('attrImplMax', fpct(max(imp), 0))
        N('attrErrMin', fpct(min(err), 0))
        N('attrErrMax', fpct(max(err), 0))
    if a.recert_r and os.path.exists(a.recert_r):
        for name, v in json.load(open(a.recert_r)).items():
            k = RMETH[name]
            N(f'n{k}AtRq', fint(v['Rq']))
            N(f'n{k}AtR', fint(v['R']))
    if a.summary_r and os.path.exists(a.summary_r):
        S = json.load(open(a.summary_r))
        for name, v in S['main'].items():
            k = RMETH.get(name)
            if k not in ('CGR', 'FZR', 'PVR'):
                continue
            for t in ('L1f', 'L2', 'Rq', 'R', 'R2'):
                N(f'n{k}At{t.replace("1f", "onef").replace("2", "two")}', fint(v[t]))
            N(f'p{k}AtR', fpct(v['R'] / S['n_exc']))
        for t in S['tests']:
            k = RMETH[t['a']] + 'vs' + RMETH[t['b']] + t['tier']
            N(f't{k}Diff', fint(t['diff']) if t['diff'] >= 0 else '$-$' + fint(-t['diff']))
            lo, hi = t['ci95']
            N(f't{k}CI', f'[{fint(lo) if lo >= 0 else "$-$" + fint(-lo)}, {fint(hi) if hi >= 0 else "$-$" + fint(-hi)}]')
            N(f't{k}AOnly', fint(t['a_only']))
            N(f't{k}BOnly', fint(t['b_only']))
            N(f't{k}P', fp(t['p']))
        for name, v in S.get('known_positive_recall', {}).items():
            k = RMETH[name]
            for t in ('L1f', 'R'):
                N(f'r{k}At{t.replace("1f", "onef")}', fpct(v[t]))
        for src, v in S.get('attribution', {}).items():
            if src.startswith('_'):
                N('attrRAgree', fpct(v['agree'] / v['n'], 0))
                N('attrRKappa', f"{v['kappa']:.2f}")
                continue
            k = ATTR.get(src)
            if k is None:
                continue
            N(f'p{k}Impl', fpct(v['implausible_share'], 0))
            N(f'p{k}Meaningful', fpct(v['meaningful_share'], 0))
            N(f'p{k}Err', fpct(v['errors'] / v['n'], 0))
            rows.append((src, dict(n=v['n'], counts=v['counts'], certified=None)))
        if 'h6' in S:
            h = S['h6']
            N('hSixDiff', fint(round(h['diff'])) if h['diff'] >= 0 else '$-$' + fint(round(-h['diff'])))
            lo, hi = h['ci95']
            N('hSixCI', f'[{fint(round(lo)) if lo >= 0 else "$-$" + fint(round(-lo))}, {fint(round(hi))}]')
            N('hSixP', f"{h['p_one_sided']:.3f}")
        if 'h7' in S:
            N('hSevenP', fp(S['h7']['p_one_sided']))
        for name, v in S.get('time_to_witness_R', {}).items():
            k = RMETH.get(name)
            if k:
                N(f't{k}RMedian', f"{v['median']:.2f}")
                N(f't{k}RWithinOne', fpct(v['within1']))
        if 'calibration' in S:
            N('calibSame', f"{S['calibration']['same']} of {S['calibration']['n']}")
        for src, v in S.get('estimated_meaningful', {}).items():
            k = ATTR.get(src)
            if k and 'errors_estimate' in v:
                N(f'est{k}Err', fint(round(v['errors_estimate'])))
            if k:
                N(f'est{k}Meaningful', fint(round(v['estimate'])))
                N(f'est{k}MeaningfulCI', f"[{fint(round(v['ci95'][0]))}, {fint(round(v['ci95'][1]))}]")
    if a.summary_r and os.path.exists(a.summary_r):
        AB = json.load(open(a.summary_r)).get('ablation_R')
        if AB:
            nm = {'CaliberGraph-R': 'Full', '-real sub-databases': 'NoReal', '-synthesis': 'NoSyn', '-anchoring': 'NoAnchor',
                  '-join completion': 'NoJoin', 'Random fuzzing-R': 'Fuzz', 'ParSEval-R': 'PV'}
            N('nSubR', fint(AB['n']))
            for k, v in json.load(open(a.summary_r)).get('ablation_R_tests', {}).items():
                nm2 = {'-real sub-databases': 'NoReal', '-synthesis': 'NoSyn', '-anchoring': 'NoAnchor', '-join completion': 'NoJoin'}[k]
                N(f'ablR{nm2}P', fp(v['p']))
            c = AB['counts']
            if 'ParSEval-R' in c and 'CaliberGraph-R' in c and c['ParSEval-R']['R'] == 0:
                N('hFivePVP', fp(min(1.0, 2 * 0.5 ** c['CaliberGraph-R']['R'])))
            full = AB['counts'].get('CaliberGraph-R', {}).get('R')
            rows_ = []
            for k, v in AB['counts'].items():
                N('ablR' + nm.get(k, k.replace(' ', '')), fint(v['R']))
                d = '' if full is None or k == 'CaliberGraph-R' or not k.startswith('-') else f"{v['R'] - full:+d}".replace('-', '$-$')
                rows_.append(f"{k.replace('-', '$-$', 1) if k.startswith('-') else k} & {fint(v['R'])} & {d} \\\\")
            tab('rablation', a.paper, ['\\begin{tabular}{lrr}', '\\toprule', 'Configuration & $\\mathcal A_R$ witnesses & $\\Delta$ \\\\',
                                       '\\midrule', *rows_, '\\bottomrule', '\\end{tabular}'])
    hc = os.path.join(os.path.dirname(__file__), '..', 'results', 'audit', 'human_check_R_summary.json')
    if os.path.exists(hc):
        H = json.load(open(hc))
        N('hcRSummary', f"stratified by the adjudicated verdict to test agreement, not to estimate shares: the author agreed with the adjudicated verdict on {H['agree_final']} of {H['n']} items, with each pass on {H['agree_a']} and {H['agree_b']}, and with at least one pass on {H['agree_any']}; the two disagreements exchange one implausible and one gold-error judgement")
    if a.issues and os.path.exists(a.issues):
        I = json.load(open(a.issues))
        N('nIssues', fint(len(I)))
        N('nIssuesGold', fint(sum(1 for x in I if x['kind'] == 'gold_wrong')))
        N('nIssuesAmb', fint(sum(1 for x in I if x['kind'] == 'ambiguous')))
    if a.summary_r and os.path.exists(a.summary_r):
        SR = json.load(open(a.summary_r))
        per = SR.get('per_system_R')
        if per:
            sh = [v['r_share'] for v in per.values()]
            N('rShareMin', fpct(min(sh)))
            N('rShareMax', fpct(max(sh)))
            at = SR.get('attribution', {}).get('CaliberGraph-R@R')
            if at:
                e = at['errors'] / at['n']
                pts = [v['r_witnesses'] * e / v['n'] for v in per.values()]
                N('errPtsMin', f'{100 * min(pts):.1f}')
                N('errPtsMax', f'{100 * max(pts):.1f}')
    rm = []
    if a.recert_r and os.path.exists(a.recert_r):
        for name, v in json.load(open(a.recert_r)).items():
            rm.append((name, 'first', v.get('L1f'), v['Rq'], v['R']))
    if a.summary_r and os.path.exists(a.summary_r):
        S2 = json.load(open(a.summary_r))
        for name, v in S2['main'].items():
            if RMETH.get(name) in ('CGR', 'FZR', 'PVR'):
                rm.append((name, 'second', v['L1f'], v['Rq'], v['R']))
    if rm:
        lines = ['\\begin{tabular}{llrrr}', '\\toprule', 'Method & Freeze & $\\mathcal A_{1f}$ & $\\mathcal A_{Rq}$ & $\\mathcal A_R$ \\\\', '\\midrule']
        for name, fr, l1, rq, r in rm:
            nm = name + (' (subsample)' if name == 'ParSEval-R' else '')
            nm = '\\textbf{' + nm + '}' if name == 'CaliberGraph-R' else nm
            lines.append(f'{nm} & {fr} & {fint(l1) if l1 is not None else "--"} & {fint(rq)} & {fint(r)} \\\\')
        lines += ['\\bottomrule', '\\end{tabular}']
        tab('rmain', a.paper, lines)
    if rows:
        lines = ['\\begin{tabular}{lrrrrrr}', '\\toprule',
                 'Method (tier) & $n$ & Pred.\\ error & Gold error & Ambiguous & Implausible & Meaningful \\\\', '\\midrule']
        order = ['CaliberGraph@L1f', 'Fuzz@L1f', 'ParSEval-L1@L1f', 'SpotIt@L0', 'SpotIt+@L0', 'CaliberGraph-R@R', 'Fuzz-R@R']
        rows.sort(key=lambda r: order.index(r[0]) if r[0] in order else 99)
        first_r = True
        for src, v in rows:
            if src.endswith('@R') and first_r:
                lines.append('\\midrule')
                first_r = False
            c = v['counts']
            n = v['n']
            m = n - c.get('implausible_data', 0)
            lines.append(f"{src.replace('Fuzz', 'Random fuzzing').replace('@', ' (').replace('L1f', '$\\mathcal A_{1f}$').replace('L0', '$\\mathcal A_0$').replace(' (R', ' ($\\mathcal A_R$')}"
                         f"{')' if '@' in src else ''} & {n} & {c.get('pred_wrong', 0) + c.get('both_wrong', 0)} & {c.get('gold_wrong', 0)} & "
                         f"{c.get('ambiguous', 0)} & {c.get('implausible_data', 0)} & {m} \\\\")
        lines += ['\\bottomrule', '\\end{tabular}']
        tab('attribution', a.paper, [x.replace('\\\\', '\\\\') for x in lines])


def tab(name, paper, lines):
    os.makedirs(os.path.join(paper, 'tables'), exist_ok=True)
    with open(os.path.join(paper, 'tables', f'{name}.tex'), 'w') as f:
        f.write('% generated by src/make_numbers.py -- do not edit by hand\n' + '\n'.join(lines) + '\n')


