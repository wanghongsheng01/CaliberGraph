"""Generate the ICDE per-system table: EX, the count-based correction with CaliberGraph's A_1f witnesses,
and error-weighted over-statements at A_1f and A_R (certified share x attributed prediction-error rate of
the tool's random attribution sample). The error-weighted figures are lower bounds, since attribution
judges the returned witness rather than the pair.
Usage: python make_system_table.py ../results/test/summary.json ../results/test_r/summary_r.json \
          ../results/audit/test_v4_attribution_summary.json ../paper_icde/tables/systems_icde.tex
"""
import json
import sys


def main(s1, s2, a1, dst):
    from scipy.stats import kendalltau
    A = json.load(open(s1))
    B = json.load(open(s2))
    att_r = B['attribution']['CaliberGraph-R@R']
    e_r = att_r['errors'] / att_r['n']
    cg = json.load(open(a1))['methods']['CaliberGraph@L1f']
    e_1f = cg['errors'] / cg['n']
    rows = []
    for k, v in A['per_system'].items():
        r = B['per_system_R'][k]
        n = v['n']
        rows.append(dict(name=v['name'], ex=100 * v['ex'], fp=100 * v['fp_share'], corr=100 * v['corrected'],
                         e1f=100 * v['cg_fp'] * e_1f / n, cR=100 * r['r_witnesses'] / n, eR=100 * r['r_witnesses'] * e_r / n))
    rows.sort(key=lambda x: -x['ex'])
    for key, rk in (('ex', 'rex'), ('corr', 'rcorr')):
        for i, x in enumerate(sorted(rows, key=lambda x: -x[key])):
            x[rk] = i + 1
    tau = {k: kendalltau([x['ex'] for x in rows], [x['ex'] - x[k] for x in rows]).statistic for k in ('e1f', 'eR')}
    out = ['% generated by src_r/make_system_table.py -- do not edit by hand',
           '%% error rates: A_1f %.3f (CaliberGraph sample), A_R %.3f (CaliberGraph-R sample)' % (e_1f, e_r),
           '%% Kendall tau_b of EX vs EX minus error-weighted points: A_1f %.2f, A_R %.2f' % (tau['e1f'], tau['eR']),
           '\\begin{tabular}{@{}lrrrrrr@{}}', '\\toprule',
           ' & & \\multicolumn{2}{c}{Count-based, $\\mathcal A_{1f}$} & Count-based & \\multicolumn{2}{c}{Error-weighted pts}\\\\',
           '\\cmidrule(lr){3-4}\\cmidrule(lr){5-5}\\cmidrule(l){6-7}',
           "System & EX (rank) & wit.\\ \\% & EX$'$ (rank) & $\\mathcal A_R$ pts & $\\mathcal A_{1f}$ & $\\mathcal A_R$\\\\", '\\midrule']
    for x in rows:
        out.append(f"{x['name']} & {x['ex']:.1f} ({x['rex']}) & {x['fp']:.1f} & {x['corr']:.1f} ({x['rcorr']}) & "
                   f"{x['cR']:.1f} & {x['e1f']:.1f} & {x['eR']:.1f}\\\\")
    out += ['\\bottomrule', '\\end{tabular}']
    open(dst, 'w').write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main(*sys.argv[1:])
