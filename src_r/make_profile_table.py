"""Generate the ICDE table on the data profile and its violations (from profile_stats.json).
Usage: python make_profile_table.py ../results/test/profile_stats.json ../paper_icde/tables/profile_icde.tex
"""
import json
import sys


def f(x, n=None):
    # x is a percentage already rounded to one decimal; with n, recover the count and round the exact share
    # half up (rounding the rounded value again turned 20.52 into 20)
    if n:
        k = round(x * n / 100)
        return str(int(100 * k / n + 0.5))
    return f'{x:.0f}'


def main(src, dst):
    S = json.load(open(src))
    P = S['profile_total']
    V = S['violations']
    tools = ['CaliberGraph', 'Random fuzzing', 'ParSEval-L1']
    rows = [
        ('Column domains', f"{P['columns']} cols ({P['categorical']} cat.)", 'domain'),
        ('\\texttt{NULL} where never \\texttt{NULL}', f"{P['never_null']} cols", 'null'),
        ('Unique column combinations', f"{P['ucc']}", 'ucc'),
        ('Inclusion dependencies', f"{P['ind_fk']} FK + {P['ind_total']} total", 'ind'),
        ('Value dependencies', f"{P['fd_map']} + {P['cross']} cross", 'valuedep'),
        ('Lookup-table contents', f"{P['lookup']} tables", 'lookup'),
        ('Symmetric/irreflexive', f"{P['symmetric']}", 'symmetric'),
        ('Year--date agreement', f"{P['year_date']}", 'year_date'),
    ]
    out = ['% generated by src_r/make_profile_table.py -- do not edit by hand',
           '\\begin{tabular}{@{}lr' + 'r' * len(tools) + '@{}}', '\\toprule',
           ' & & \\multicolumn{%d}{c}{Witnesses violating (\\%%)}\\\\' % len(tools),
           '\\cmidrule(l){3-%d}' % (2 + len(tools)),
           'Constraint class & $|\\Pi|$ on BIRD & CG & Fuzz & PSE\\\\', '\\midrule']
    for name, size, k in rows:
        out.append(f'{name} & {size} & ' + ' & '.join(f(V[t]['referenced'][k], V[t]['n']) for t in tools) + '\\\\')
    out.append('\\midrule')
    out.append('Witnesses $n$ & & ' + ' & '.join(f"{V[t]['n']:,}".replace(',', '{,}') for t in tools) + '\\\\')
    out += ['\\bottomrule', '\\end{tabular}']
    open(dst, 'w').write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main(*sys.argv[1:])
