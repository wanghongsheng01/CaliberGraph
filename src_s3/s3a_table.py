"""Pre-registered decision rule of S3-A / 17b: human estimates next to AI estimates.
Writes paper_pvldb/tables/humanai.tex: label distribution per round and stage, AI vs. human consensus (items on which
both annotators agree; disagreements counted separately). Usage: python src_s3/s3a_table.py"""
import json, os, re, sys
from collections import Counter
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
sys.path.insert(0, os.path.join(ROOT, 'src_r'))
from human_validation import parse  # noqa: E402
L = ['pred_wrong', 'both_wrong', 'gold_wrong', 'ambiguous', 'implausible_data']
rows = []
out = {}
for rnd, d, s1, s2 in (('1', 'human_validation', 'sheet_annotator1.md', 'sheet_annotator2.md'),
                       ('2', 'human_validation_r2', 'sheet_r2_annotator1.md', 'sheet_r2_annotator2.md')):
    D = os.path.join(ROOT, 'results', 'audit', d)
    key = {k['no']: k for k in json.load(open(os.path.join(D, 'key_DO_NOT_OPEN_BEFORE_ANNOTATING.json')))}
    a, b = parse(os.path.join(D, s1)), parse(os.path.join(D, s2))
    for st in (1, 2):
        ids = [i for i in key if (re.match(r'(CaliberGraph-R|Fuzz-R)@', key[i]['source']) is not None) == (st == 2)]
        ai = Counter(key[i]['ai'] for i in ids)
        hc = Counter(a[i] if a[i] == b[i] else 'disagree' for i in ids)
        out[f'r{rnd}s{st}'] = dict(n=len(ids), ai=dict(ai), human=dict(hc))
        rows.append((rnd, st, len(ids), ai, hc))
# round 3 (docs/en/17c): three annotators; humans = majority label (>= 2 of 3); Dis. = no majority
sys.path.insert(0, os.path.dirname(__file__))
from hv3_check import split_items, verdict  # noqa: E402
D3 = os.path.join(ROOT, 'results', 'audit', 'human_validation_r3')
key3 = {k['code']: k for k in json.load(open(os.path.join(D3, 'key_DO_NOT_OPEN_BEFORE_ANNOTATING.json')))}
H3 = []
for w in 'ABC':
    _, it = split_items(open(os.path.join(D3, f'sheet_r3_annotator{w}.md')).read())
    H3.append({c: verdict(b)[0] for c, b in it.items()})
for st in (1, 2):
    ids = [c for c in sorted(key3) if key3[c]['stage'] == st]
    ai = Counter(key3[c]['ai'] for c in ids)
    hc = Counter()
    for c in ids:
        v, n = Counter(h[c] for h in H3).most_common(1)[0]
        hc[v if n >= 2 else 'disagree'] += 1
    out[f'r3s{st}'] = dict(n=len(ids), ai=dict(ai), human=dict(hc))
    rows.append(('3', st, len(ids), ai, hc))
json.dump(out, open(os.path.join(ROOT, 'results', 'stage3', 's3a_humanai_table.json'), 'w'), indent=1)
tex = [r'% generated by src_s3/s3a_table.py', r'\begin{table}[t]', r'\centering\scriptsize',
       r'\caption{Human estimates next to the AI estimates (pre-registered reporting rule): verdicts on the same blind items, per round and stage (stage 1: schema-tier witnesses; stage 2: $\mathcal A_R$). Humans: rounds 1--2, items on which both annotators agree (Dis.: they disagree); round 3, the label of at least two of three annotators (Dis.: no majority). Round 1 showed only the witness, rounds 2--3 also facts of $D_0$. AI counts are over all items (R3-4 in Table~\ref{tab:hypotheses} compares the 64 stage-2 items with a majority).}\label{tab:humanai}',
       r'\setlength{\tabcolsep}{3pt}', r'\begin{tabular}{@{}llrrrrrrr@{}}', r'\toprule',
       r'Round & Stage, judge & $n$ & Pred.\ err. & Both & Gold err. & Ambig. & Implaus. & Dis.\\', r'\midrule']
for rnd, st, n, ai, hc in rows:
    for who, c in (('AI', ai), ('humans', hc)):
        tex.append(f"{rnd if (st == 1 and who == 'AI') else ''} & {st}, {who} & {n} & " +
                   ' & '.join(str(c.get(l, 0)) for l in L) + f" & {c.get('disagree', 0) if who == 'humans' else ''}\\\\")
    if not (rnd == '3' and st == 2):
        tex.append(r'\addlinespace[1pt]' if st == 1 else r'\midrule')
tex += [r'\bottomrule', r'\end{tabular}', r'\end{table}']
open(os.path.join(ROOT, 'paper_pvldb', 'tables', 'humanai.tex'), 'w').write('\n'.join(tex) + '\n')
if os.path.isdir(os.path.join(ROOT, 'paper_is', 'tables')):  # journal version: floats placed here/top/bottom/page
    open(os.path.join(ROOT, 'paper_is', 'tables', 'humanai.tex'), 'w').write('\n'.join(tex).replace('\\begin{table}[t]', '\\begin{table}[!htbp]') + '\n')
print('\n'.join(tex))
